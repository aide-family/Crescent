#!/usr/bin/env node
const fs = require('fs')
const { execSync } = require('child_process')

const GIT_COMMIT_RE = /(?:^|[\s;|&])git(?:\s+-C\s+\S+)?\s+commit\b/
const AUTHOR_FLAG_RE = /(?:^|[\s;|&])git(?:\s+-C\s+\S+)?\s+commit\b[\s\S]*?--author\b/
const NO_VERIFY_RE = /(?:^|[\s;|&])git(?:\s+-C\s+\S+)?\s+commit\b[\s\S]*?--no-verify(?:\s|$)/
const CURSOR_LINE_RE =
  /^\s*(Co-authored-by:\s*.*\b(Cursor|cursoragent)\b|Made-with:\s*Cursor|Generated by Cursor)\s*$/i

function isGitCommitCommand(command) {
  return GIT_COMMIT_RE.test(String(command || ''))
}

function hasAuthorOverride(command) {
  return AUTHOR_FLAG_RE.test(String(command || ''))
}

function skipsHooks(command) {
  return NO_VERIFY_RE.test(String(command || ''))
}

function hasCursorAttribution(text) {
  const value = String(text || '')
  if (/cursoragent@cursor\.com/i.test(value)) return true
  if (/Co-authored-by:\s*Cursor\b/i.test(value)) return true
  if (/Made-with:\s*Cursor/i.test(value)) return true
  if (/Generated by Cursor/i.test(value)) return true
  return false
}

function stripCursorTrailers(message) {
  return String(message || '')
    .split('\n')
    .filter((line) => !CURSOR_LINE_RE.test(line) && !/cursoragent@cursor\.com/i.test(line))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/\s+$/g, '\n')
}

function evaluateCommitCommand(command) {
  if (!isGitCommitCommand(command)) return { ok: true }
  if (skipsHooks(command)) {
    return {
      ok: false,
      reason: 'Do not skip git hooks (--no-verify). Local CI must run before every commit.'
    }
  }
  if (hasAuthorOverride(command)) {
    return {
      ok: false,
      reason: 'Do not pass --author. Commits must use the repository git user only.'
    }
  }
  return { ok: true }
}

function readGitIdent() {
  const name = execSync('git config user.name', { encoding: 'utf8' }).trim()
  const email = execSync('git config user.email', { encoding: 'utf8' }).trim()
  if (!name || !email) {
    throw new Error('git user.name and user.email must be set for this repository.')
  }
  return { name, email }
}

function parseAuthorIdent(ident) {
  const match = String(ident || '').match(/^(.*) <([^>]+)>/)
  if (!match) return null
  return { name: match[1].trim(), email: match[2].trim() }
}

function evaluateAuthorIdent(authorIdent, repoIdent) {
  const author = parseAuthorIdent(authorIdent)
  if (!author) {
    return { ok: false, reason: 'Could not read GIT_AUTHOR_IDENT.' }
  }
  if (author.name !== repoIdent.name || author.email !== repoIdent.email) {
    return {
      ok: false,
      reason: `Commit author must be the repository git user (${repoIdent.name} <${repoIdent.email}>), not ${author.name} <${author.email}>.`
    }
  }
  return { ok: true }
}

function readStdin() {
  return fs.readFileSync(0, 'utf8')
}

function allow(payload) {
  process.stdout.write(`${JSON.stringify(payload)}\n`)
}

function runCommitMsg(filePath) {
  const original = fs.readFileSync(filePath, 'utf8')
  const next = stripCursorTrailers(original)
  if (next !== original) fs.writeFileSync(filePath, next)
  if (hasCursorAttribution(next)) {
    console.error('Commit message still contains Cursor attribution after cleanup.')
    process.exit(1)
  }
}

function runPreCommitAuthor() {
  const repoIdent = readGitIdent()
  const authorIdent = execSync('git var GIT_AUTHOR_IDENT', { encoding: 'utf8' }).trim()
  const result = evaluateAuthorIdent(authorIdent, repoIdent)
  if (!result.ok) {
    console.error(result.reason)
    process.exit(1)
  }
}

function runCursorHook() {
  let input = {}
  try {
    const raw = readStdin().trim()
    input = raw ? JSON.parse(raw) : {}
  } catch {
    allow({ permission: 'allow' })
    return
  }
  const command = typeof input.command === 'string' ? input.command : ''
  const result = evaluateCommitCommand(command)
  if (!result.ok) {
    allow({
      permission: 'deny',
      user_message: result.reason,
      agent_message: result.reason
    })
    return
  }
  allow({ permission: 'allow' })
}

const command = process.argv[2]
if (require.main === module) {
  if (command === 'commit-msg') runCommitMsg(process.argv[3])
  else if (command === 'pre-commit-author') runPreCommitAuthor()
  else if (command === 'cursor-hook') runCursorHook()
}

module.exports = {
  isGitCommitCommand,
  hasAuthorOverride,
  hasCursorAttribution,
  stripCursorTrailers,
  evaluateCommitCommand,
  evaluateAuthorIdent
}
